let _boardTab = '实力榜';
const BOARD_NAMES = ['实力榜', '财富榜', '声望榜'];
const BOARD_TITLES = { '实力榜': '仙盟实力榜', '财富榜': '仙盟财富榜', '声望榜': '仙盟声望榜' };

/** 榜位差分集：上一版快照有底时，势变/新上榜的行淡朱衬底（rankMoved 由 renderRank 写） */
let rankMoved = new Set();

function rankRows(model, board) {
    const rows = arr(model.boards?.[board]);
    if (!rows.length) return '';
    const me = model.sect;
    const list = [...rows].sort((a, b) => num(b.pow) - num(a.pow));
    return list.map((r, i) => {
        const isMe = me && r.name === me;
        const chg = String(r.chg || '');
        const cls = chg.startsWith('+') ? 'up' : chg.startsWith('-') ? 'dn' : '';
        return `<div class="zb-rk${isMe ? ' me' : ''}${rankMoved.has(r.name) ? ' moved' : ''}">
          <i class="pos p${Math.min(i + 1, 3)}">${i + 1}</i>
          <div class="rkbd"><b>${esc(r.name)}${isMe ? ' <span class="stamp zhu">本宗</span>' : ''}</b>
            <div class="bar"><i style="width:${Math.min(100, Math.max(2, num(r.pow)))}%"></i></div>
            ${r.note ? `<em>${esc(r.note)}</em>` : ''}</div>
          <span class="chg ${cls}">${esc(chg) || '—'}</span>
        </div>`;
    }).join('');
}

function renderRank(model) {
    const tabs = BOARD_NAMES.filter(b => arr(model.boards?.[b]).length);
    if (!tabs.length) return '';
    if (!tabs.includes(_boardTab)) _boardTab = tabs[0];
    // 差分：有旧底才算"变了"——初见是基线，整版不亮
    const rows = arr(model.boards?.[_boardTab]);
    const prev = prevRank[_boardTab];
    rankMoved = new Set();
    if (prev) rows.forEach(r => { if (!(r.name in prev) || prev[r.name] !== num(r.pow)) rankMoved.add(r.name); });
    prevRank[_boardTab] = Object.fromEntries(rows.map(r => [r.name, num(r.pow)]));
    const issue = Math.floor(num(model.day) / 30) * 30;
    return `<div class="zb-rank zb-card">
      <div class="hd"><span>${BOARD_TITLES[_boardTab]}</span><span class="stamp grey">执事堂颁${issue ? ` · D${issue}放榜` : ''}</span></div>
      <div class="zb-btabs">${tabs.map(b => `<button class="bt${b === _boardTab ? ' on' : ''}" data-board="${b}">${b.replace('榜', '')}</button>`).join('')}</div>
      ${rankRows(model, _boardTab)}
    </div>`;
}

