/** 事件归区：feed/due 文本按各区关键词命中（事件尚无结构化地理字段时的索引） */
function eventsInRegion(model, region) {
    const hits = [];
    for (const f of arr(model.feed)) {
        const blob = `${f.src}${f.text}`;
        if (region.kw.test(blob)) hits.push({ src: f.src, text: f.text, day: f.day });
    }
    for (const d of arr(model.due)) {
        if (region.kw.test(`${d.thing}${d.ddl}`)) hits.push({ src: '催', text: `${d.thing}（限 ${d.ddl}）`, day: null });
    }
    return hits;
}

