/** 浮钮拖拽：8px 阈值分点按与拖拽，位置记 localStorage（JSR shim 里有同款内联实现）。
 *  move/up 挂 document 不挂钮——不靠 setPointerCapture，webview 哑火也能拖全程 */
function bindLaunchDrag(btn, doc) {
    try {
        if (!btn || btn._dragBound) return;
        btn._dragBound = true;
        const LS = 'zb-launch-pos', win = doc.defaultView || window;
        const applyPos = p => {
            btn.style.left = p.x + 'px'; btn.style.top = p.y + 'px';
            btn.style.right = 'auto'; btn.style.bottom = 'auto'; btn.style.transform = 'none';
        };
        const saved = safeGet(() => JSON.parse(win.localStorage?.getItem(LS)));
        if (saved && saved.x >= 0 && saved.y >= 0 && saved.x <= win.innerWidth - 40 && saved.y <= win.innerHeight - 40) applyPos(saved);
        const start = (cx, cy) => {
            const r = btn.getBoundingClientRect(), ox = cx - r.left, oy = cy - r.top;
            let moved = false;
            const mv = ev => {
                const p = ev.touches ? ev.touches[0] : ev;
                if (!p) return;
                if (!moved && Math.hypot(p.clientX - cx, p.clientY - cy) < 8) return;
                if (!moved) { moved = true; btn._dragged = true; applyPos({ x: r.left, y: r.top }); }
                btn.style.left = Math.min(Math.max(p.clientX - ox, 0), win.innerWidth - r.width) + 'px';
                btn.style.top = Math.min(Math.max(p.clientY - oy, 0), win.innerHeight - r.height) + 'px';
                if (ev.cancelable) ev.preventDefault();
            };
            const up = () => {
                doc.removeEventListener('pointermove', mv, true); doc.removeEventListener('pointerup', up, true);
                doc.removeEventListener('touchmove', mv, true); doc.removeEventListener('touchend', up, true);
                if (moved) try { win.localStorage?.setItem(LS, JSON.stringify({ x: parseFloat(btn.style.left), y: parseFloat(btn.style.top) })); } catch { }
            };
            doc.addEventListener('pointermove', mv, true); doc.addEventListener('pointerup', up, true);
            doc.addEventListener('touchmove', mv, { capture: true, passive: false });
            doc.addEventListener('touchend', up, true);
        };
        btn.addEventListener('pointerdown', e => { e.preventDefault?.(); start(e.clientX, e.clientY); });
        btn.addEventListener('touchstart', e => { const t = e.touches[0]; if (t) start(t.clientX, t.clientY); });
    } catch { }
}

/**
 * _.set 行分流：剥出 set 行进 sets[]，剩下的是可示人的正文。
 * 兼容 <UpdateVariable>…</UpdateVariable> 包裹块（JSR/MVU 约定）与裸行。
 * 容忍上游模型掉格式：set(/_set(/＿.set( 都算；行首的列表符/引用符剥了再认；
 * 纯代码围栏行是 set 的包装纸，跟着剥——不进正文。
 */
const SET_LINE_RE = /^[_＿]?[.．]?set\s*[(（]/;
/** 引号外数括号——set 行没闭合时说明值跨了行（弱模型爱把 JSON 值折行写） */
function parenDepth(s) {
    let d = 0, q = null;
    for (let i = 0; i < s.length; i++) {
        const ch = s[i];
        if (q) { if (ch === '\\') i++; else if (ch === q) q = null; continue; }
        if (ch === "'" || ch === '"' || ch === '`') { q = ch; continue; }
        if (ch === '(' || ch === '（') d++;
        else if (ch === ')' || ch === '）') d--;
    }
    return d;
}
/** 把畸形 <update>/<JSONPatch>/<operation> 里的 patch 对象转成标准 _.set('stat_data.xxx', v) 行，走本地 setVariable 落账 */
function extractPatchSets(block, sets) {
    const pushOp = op => {
        if (!op || typeof op !== 'object') return;
        const verb = String(op.op || '').toLowerCase();
        if (!['set', 'replace', 'add'].includes(verb) || !op.path) return;
        let p = String(op.path).trim().replace(/^\/+/, '').replace(/\//g, '.');
        if (!p) return;
        if (!p.startsWith('stat_data.') && p !== 'stat_data') p = 'stat_data.' + p;
        try { sets.push(`_.set(${JSON.stringify(p)}, ${JSON.stringify(op.value)})`); } catch { }
    };
    const tryJson = raw => {
        const s = String(raw || '').trim();
        if (!s) return false;
        try {
            const parsed = JSON.parse(s);
            if (Array.isArray(parsed)) parsed.forEach(pushOp);
            else pushOp(parsed);
            return true;
        } catch { return false; }
    };
    // 1) 优先抽 <operation>{...}</operation>
    let matchedOp = false;
    for (const m of String(block).matchAll(/<operation[^>]*>([\s\S]*?)<\/operation>/gi)) {
        if (tryJson(m[1])) matchedOp = true;
    }
    if (matchedOp) return;
    // 2) 其次抽 <JSONPatch> / <json_patch> 内的纯 JSON 数组或对象
    for (const m of String(block).matchAll(/<(?:JSONPatch|json_patch)[^>]*>([\s\S]*?)<\/(?:JSONPatch|json_patch)>/gi)) {
        if (tryJson(m[1])) return;
    }
    // 3) 兜底：逐个找含 "op" 与 "path" 的扁平/嵌套 JSON 对象
    for (const m of String(block).matchAll(/\{[^{}]*"op"\s*:\s*"(?:set|replace|add)"[\s\S]*?\}/gi)) {
        tryJson(m[0]);
    }
}

function splitSetLines(text) {
    const keep = [], sets = [];
    // 先剥除并兜底提取模型脑补出的畸形 <update>/<JSONPatch>/<operation>/<analyze> 块，防止残留标签污染历史继续自我强化
    let src = String(text ?? '');
    src = src.replace(/<update\b[^>]*>([\s\S]*?)<\/update>/gi, (_, inner) => {
        extractPatchSets(inner, sets);
        // 块内若混有正常 _.set 行也一并收走
        for (const ln of inner.split('\n')) {
            const p = ln.trim().replace(/^[-*•·>\s･・●◦‣⁃]+/, '');
            if (SET_LINE_RE.test(p)) sets.push(p.replace(/\s*[>＞]+\s*$/, ''));
        }
        return '';
    });
    src = src.replace(/<(?:JSONPatch|json_patch)\b[^>]*>([\s\S]*?)<\/(?:JSONPatch|json_patch)>/gi, (_, inner) => {
        extractPatchSets('<JSONPatch>' + inner + '</JSONPatch>', sets);
        return '';
    });
    src = src.replace(/<analyze\b[^>]*>[\s\S]*?<\/analyze>/gi, '');
    src = src.replace(/<operation\b[^>]*>([\s\S]*?)<\/operation>/gi, (_, inner) => {
        extractPatchSets('<operation>' + inner + '</operation>', sets);
        return '';
    });
    // 清掉孤立/重复闭合标签（如多出来的一行 </JSONPatch> 或未闭合的 <update>）
    src = src.replace(/<\/?(?:update|JSONPatch|json_patch|operation|analyze)\b[^>]*>/gi, '');
    const lines = src.split('\n');
    let inUV = false, uvStart = -1;
    for (let i = 0; i < lines.length; i++) {
        const t = lines[i].trim();
        if (/<UpdateVariable>/i.test(t)) { inUV = true; uvStart = sets.length; continue; }
        if (/<\/UpdateVariable>/i.test(t)) { inUV = false; uvStart = -1; continue; }
        if (inUV) { sets.push(lines[i]); continue; }
        const probe = t.replace(/^[-*•·>\s･・●◦‣⁃]+/, '');
        if (SET_LINE_RE.test(probe)) {
            let joined = probe, guard = 0;
            while (parenDepth(joined) > 0 && guard < 10 && i + 1 < lines.length)
                joined += '\n' + lines[++i], guard++;
            // 兼容猫赛亚等预设把 <catgodml|...> 闭合符 '>' 贴在 _.set(...) 行尾的情况
            sets.push(joined.replace(/\s*[>＞]+\s*$/, ''));
            continue;
        }
        if (/^```[\w-]*$/.test(t)) continue;   // 围栏行——小说正文里没有合法用途，跟着 set 皮一起剥
        keep.push(lines[i]);
    }
    // 不闭合的 <UpdateVariable> 救尾：模型掉了闭合标签时尾巴整段被吞——逐行重判，只留真 set 行
    if (inUV && uvStart >= 0)
        sets.splice(uvStart).forEach(l =>
            (SET_LINE_RE.test(l.trim().replace(/^[-*•·>\s･・●◦‣⁃]+/, '')) ? sets : keep).push(l));
    // 清理剥离 _.set 后残留的空壳 <catgodml|...> 容器（有正文的容器保持原样）
    const cleaned = keep.join('\n')
        .replace(/<catgodml\|[^>\n]*\s*(?:\n\s*)?>/gi, '')
        .replace(/(?:^|\n)<catgodml\|[^>\n]*\s*$/gi, '')
        .replace(/\n{3,}/g, '\n\n')
        .trimEnd();
    return { text: cleaned, sets };
}

/** 单行 _.set 落进 stat_data（路径只收 stat_data.*；值先 JSON.parse 再字面量 eval）。
 *  返回是否真落了账——写了行但一条没落的也算漏账（格式破得解析不了），由调用处置旗催账 */
function applySetLine(sd, ln) {
    const SET_CALL_RE = /[_＿]?[.．]?set\s*\(\s*(['"‘’＇｀′“”＂])([^'"‘’＇｀′“”＂]+)\1\s*,\s*([\s\S]*)[)）]\s*[;；>＞]?\s*$/;
    let m = String(ln).match(SET_CALL_RE);
    if (!m) {
        // 全角兜底：模型掉格式（_.set（'stat_data.天数', 5））照常吃——归一后重配一次，配不上才丢
        const norm = String(ln).replace(/[（）]/g, c => c === '（' ? '(' : ')').replace(/[‘’＇｀′]/g, "'").replace(/[“”＂]/g, '"').replace(/，/g, ',').replace(/；/g, ';').replace(/：/g, ':').replace(/．/g, '.').replace(/＿/g, '_').replace(/｛/g, '{').replace(/｝/g, '}');
        if (norm !== ln) m = norm.match(SET_CALL_RE);
    }
    if (!m || !m[2].startsWith('stat_data')) return false;
    let v;
    try { v = JSON.parse(m[3]); }
    catch {
        // eval 兜底只放字面量皮：起手是 { [ ' " 数字或内置字面量才许过——模型输出是数据不是代码
        const raw = m[3].trim();
        if (!/^[[{'"0-9\-+]/.test(raw) && !/^(true|false|null|undefined|NaN|Infinity)\b/.test(raw)) return false;
        try { v = new Function('return (' + raw + ')')(); } catch { return false; }
    }
    const seg = m[2].replace(/\[['"]([^'"]+)['"]\]/g, '.$1').replace(/^stat_data\.?/, '').split('.').filter(Boolean);
    if (!seg.length) { if (v && typeof v === 'object') Object.assign(sd, v); return true; }   // _.set('stat_data',{…}) 整树并入
    // 根键中英/别名归一：模型偶尔自造英文根键（facility/inventory/roster/duties/feed/resources等），全部无损归一到标准中文根键
    const ROOT_ALIAS = {
        '物品': '行囊', '仓库': '行囊', '背包': '行囊', 'inventory': '行囊', 'items': '行囊', 'item': '行囊', 'bag': '行囊', 'pack': '行囊',
        '建筑': '设施', 'facility': '设施', 'facilities': '设施', 'building': '设施', 'buildings': '设施',
        '弟子': '名册', 'roster': '名册', 'disciples': '名册', 'disciple': '名册',
        '事务': '日务', '任务': '日务', 'duties': '日务', 'duty': '日务', 'tasks': '日务', 'daily': '日务',
        '日报': '渠道队', '周报': '渠道队', '报馆': '渠道队', '报纸': '渠道队', 'feed': '渠道队', 'news': '渠道队', 'newspaper': '渠道队',
        'resources': '资源', 'resource': '资源', 'res': '资源',
        'ledger': '牵扯', 'debts': '牵扯', 'debt': '牵扯',
        'faction': '势力', 'factions': '势力',
        'due': '待回话', 'pending': '待回话',
        'sect_events': '山门事', 'sectevents': '山门事', 'events': '山门事',
        'arcs': '主线', 'arc': '主线', 'main': '主线',
    };
    const rootLow = String(seg[0] || '').toLowerCase().replace(/[_\-\s]+/g, '');
    if (ROOT_ALIAS[seg[0]]) seg[0] = ROOT_ALIAS[seg[0]];
    else if (ROOT_ALIAS[rootLow]) seg[0] = ROOT_ALIAS[rootLow];
    // 子字段英文别名归一（如 stat/status -> 状，level -> 级，done -> 完，effect -> 效）
    const SUB_KEY_ALIAS = {
        'stat': '状', 'status': '状', 'state': '状', '状态': '状',
        'level': '级', 'lv': '级', '等级': '级',
        'done': '完', 'doneday': '完', 'eta': '完', 'finish': '完', '完工日': '完',
        'effect': '效', 'fx': '效', '效用': '效',
        'note': '注', 'desc': '注', '备注': '注',
        'traits': '词条', 'tags': '词条', '标签': '词条',
        'upgrades': '升次', '升级次数': '升次',
        'targetlv': '目标级',
        'name': '名', 'title': '题', 'text': '文', 'content': '文', 'src': '源', 'source': '源',
    };
    const normSubKey = (root, k) => {
        if (root === '名册' && (k === 'status' || k === '状态')) return '状态';
        const low = String(k || '').toLowerCase().replace(/[_\-\s]+/g, '');
        return SUB_KEY_ALIAS[k] ?? SUB_KEY_ALIAS[low] ?? k;
    };
    // 容错：_.set('stat_data.行囊', {名:...}) 传单件对象时按同名更新或追加，绝不覆盖清空整袋行囊
    if (seg.length === 1 && seg[0] === '行囊' && v && typeof v === 'object' && !Array.isArray(v)) {
        if (!Array.isArray(sd['行囊'])) sd['行囊'] = objArr(sd['行囊']);
        const nm = v['名'] ?? v.name;
        const exist = nm ? sd['行囊'].findIndex(x => x && (x['名'] ?? x.name) === nm) : -1;
        if (exist >= 0) sd['行囊'][exist] = { ...sd['行囊'][exist], ...v };
        else sd['行囊'].push(v);
        return true;
    }
    // 局部对象浅合并：_.set('stat_data.资源', {'灵石':260}) 或 _.set('stat_data.主线', {'借宗':'酝酿'}) 只更新变动键，绝不把声望/士气或其他主线抹空
    if (seg.length === 1 && (seg[0] === '资源' || seg[0] === '主线') && v && typeof v === 'object' && !Array.isArray(v)) {
        sd[seg[0]] = { ...(sd[seg[0]] && typeof sd[seg[0]] === 'object' ? sd[seg[0]] : {}), ...v };
        return true;
    }
    // 智能数组按名寻址与浅合并：全面覆盖 设施/行囊/名册/日务/待回话/牵扯/势力/山门事，
    // 支持按名定位（如 设施.前坪.完 / 行囊.残丹谱.状 / 势力.清源观.好感 / 牵扯.玄阙仙业信托.结），
    // 且当 AI 猜错数字下标但写了主标识字段时自动重定位到真实下标并合并原字段，绝不丢数据或覆错对象
    const ARRAY_KEY_SPEC = {
        '设施': { field: '地', norm: s => aliasPlace(String(s || '').trim()) },
        '行囊': { field: '名', altField: '号', norm: s => String(s || '').trim() },
        '名册': { field: '名', norm: s => String(s || '').trim() },
        '日务': { field: '事', norm: s => String(s || '').trim() },
        '待回话': { field: '事', norm: s => String(s || '').trim() },
        '牵扯': { field: '对方', norm: s => String(s || '').trim() },
        '势力': { field: '名', norm: s => String(s || '').trim() },
        '山门事': { field: '事', norm: s => String(s || '').trim() },
        '渠道队': { field: '题', altField: '文', norm: s => String(s || '').trim().slice(0, 16) },
    };
    const spec = ARRAY_KEY_SPEC[seg[0]];
    if (spec && seg.length >= 2) {
        if (!Array.isArray(sd[seg[0]])) sd[seg[0]] = objArr(sd[seg[0]]);
        const list = sd[seg[0]];
        const rawIdx = seg[1];
        const isNum = /^\d+$/.test(rawIdx);
        const isAppend = !isNum && /^(新|add|push|append|new|\+)$/i.test(rawIdx);
        let idxPos = -1;
        if (isNum) {
            idxPos = Number(rawIdx);
            // 若直接写对象且带了主标识字段（如 设施.0 写了 地:'前坪'），按主标识重定位防 AI 猜错下标覆错别人
            if (seg.length === 2 && v && typeof v === 'object' && !Array.isArray(v)) {
                const vKey = spec.norm(v[spec.field] ?? '');
                const curKey = list[idxPos] ? spec.norm(list[idxPos][spec.field] ?? '') : '';
                if (vKey && vKey !== curKey) {
                    const real = list.findIndex(x => x && spec.norm(x[spec.field]) === vKey);
                    if (real >= 0) idxPos = real;
                    else if (seg[0] === '渠道队' && list[idxPos]) idxPos = list.length;   // 新闻不覆盖旧报，自动追加
                }
            }
        } else if (!isAppend) {
            const target = spec.norm(rawIdx);
            idxPos = list.findIndex(x => x && (spec.norm(x[spec.field]) === target || (spec.altField && spec.norm(x[spec.altField]) === target)));
            if (idxPos < 0 && target) {
                idxPos = list.length;
                list.push({ [spec.field]: target });
            }
        } else {
            idxPos = list.length;
        }
        if (seg.length === 2) {
            if (v && typeof v === 'object' && !Array.isArray(v) && list[idxPos] && typeof list[idxPos] === 'object') {
                // 词条追加去重：若更新设施时写入了新词条且原来也有词条，自动合并保留历史词条
                const merged = { ...list[idxPos], ...v };
                if (seg[0] === '设施' && list[idxPos]['词条'] && v['词条']) {
                    const oldT = Array.isArray(list[idxPos]['词条']) ? list[idxPos]['词条'] : String(list[idxPos]['词条']).split(/[、，,|｜]/);
                    const newT = Array.isArray(v['词条']) ? v['词条'] : String(v['词条']).split(/[、，,|｜]/);
                    merged['词条'] = [...new Set([...oldT, ...newT].map(x => String(x || '').trim()).filter(Boolean))];
                }
                list[idxPos] = merged;
            } else {
                list[idxPos] = v;
            }
            return true;
        }
        // 深层属性赋值（如 设施.前坪.完 / 设施.zhang_fang.stat / 行囊.耐火灵砖.状）
        if (!list[idxPos] || typeof list[idxPos] !== 'object') list[idxPos] = {};
        let cur = list[idxPos];
        const rest = seg.slice(2).map(k => normSubKey(seg[0], k));
        while (rest.length > 1) {
            const k = rest.shift(), nxt = rest[0];
            cur = cur[k] = (cur[k] && typeof cur[k] === 'object') ? cur[k] : (/^\d+$/.test(nxt) ? [] : {});
        }
        cur[rest[0]] = v;
        return true;
    }
    let cur = sd;
    // lodash 语义：下一级键是纯数字建数组不是对象——'日务.0' 这类索引写不进对象容器，arr() 会整个吞掉
    while (seg.length > 1) { const k = seg.shift(), nxt = seg[0]; cur = cur[k] = (cur[k] && typeof cur[k] === 'object') ? cur[k] : (/^\d+$/.test(nxt) ? [] : {}); }
    // 容错：对数组写了非数字追加键（如 待回话.新）自动 push，防止 JSON.stringify 静默丢弃
    if (Array.isArray(cur) && !/^\d+$/.test(seg[0])) {
        if (v !== null && v !== undefined) cur.push(v);
        return true;
    }
    cur[seg[0]] = v;
    return true;
}

export async function init(ctx) {
    if (ctx?.dead) return;   // JSR 让位：另一路案头已在跑
    if (ctx.charId && !ctx.parentDoc && ctx.container?.ownerDocument?.getElementById('zb-wrap')) {
        console.log('[总簿] JSR 案头在场，Luker 侧让位');   // 双宿主同卡同跑时只活一路
        return;
    }
    let model = readState(ctx);
    ASSET_ROOT = ctx.charId ? `/api/card-app/${encodeURIComponent(ctx.charId)}/` : '';
    if (ctx.charId && !ctx.parentDoc) adoptOverlayMode(ctx);   // Luker 整屏接管 → 浮层
    dressLaunch(ctx);   // 登记页也可能露出浮钮——上皮不等到建壳
    await loadUiPrefs(ctx);
    await buildEvtIndex(ctx);   // 异步预建事件 id→正文 索引，FINALIZED 直推用
    if (model.empty) { renderIntro(ctx); ctx.container.dataset.gate = 'init'; }
    else { model = mountDesk(ctx); ctx.container.dataset.gate = 'on'; }

    const refresh = () => {
        if (ctx.container.dataset.init === '1') return;   // 登记表在屏，别盖
        model = readState(ctx);
        if (model.empty) { renderIntro(ctx); return; }
        render(ctx, model);
        pushGateLine(ctx, model);
    };

    const onCharMsg = async () => {
        try {
            const chat = ctx.lukerContext?.chat;
            const i = (chat?.length ?? 0) - 1;
            const m = chat?.[i];
            if (!m || m.is_user) return;
            const raw = m.mes ?? m.message ?? '';
            // 重打守卫：账底认得这条（原文或剥后净文）→ 账已收过，别再把剥了皮的消息当漏账、把旧基线再快照一遍
            if (ledgerEntry(i, raw)) return;
            // prev 只描述"末位消息"的账前基线——新的末位落地，属于别条的旧基线就是上膛的枪，先卸
            if (ctx.getVariable?.('stat_data_prev_for') != null && ctx.getVariable('stat_data_prev_for') !== i) await clearPrev();
            // 同位换内容=换分支（有的宿主换版走 charMsg 不走 swiped）——名下基线在就先回基线，别叠上个分支的账
            if (ledgerSameId(i) && ctx.getVariable?.('stat_data_prev_for') === i) {
                const p = ctx.getVariable('stat_data_prev');
                if (p && typeof p === 'object') await ctx.setVariable('stat_data', p);
            }
            const { text, sets } = splitSetLines(raw);
            if (!sets.length) {
                uiLedgerMiss = true; saveUiPrefs(ctx);
                // 即使模型没写 set 行，若本轮是「度过今日」仍需先照基线再补拨天数；否则清空旧 prev
                if (pendingAdvanceDay != null && typeof ctx.getVariable === 'function' && typeof ctx.setVariable === 'function') {
                    const sd = ctx.getVariable('stat_data') || {};
                    const snap = JSON.parse(JSON.stringify(sd));
                    if (bumpPendingDay(sd)) {
                        try {
                            if (ctx.getVariable('stat_data_prev_for') !== i) {
                                await ctx.setVariable('stat_data_prev', snap);
                                await ctx.setVariable('stat_data_prev_for', i);
                            }
                        } catch { }
                        await ctx.setVariable('stat_data', sd);
                    } else {
                        await clearPrev();
                    }
                } else {
                    await clearPrev();
                }
                console.log('[总簿] 本条回复无 set 行——账未动（模型没写账，上游格式差异与契约服从性皆可能）；下轮门线将顶脸催账');
                return;
            }
            if (typeof ctx.getVariable === 'function' && typeof ctx.setVariable === 'function') {
                const sd = ctx.getVariable('stat_data') || {};
                // 账前快照必须在套用 sets 与过日补账之前拍摄——滑动换版/删消息时天数才能完整回滚
                try {
                    if (ctx.getVariable('stat_data_prev_for') !== i) {
                        await ctx.setVariable('stat_data_prev', JSON.parse(JSON.stringify(sd)));
                        await ctx.setVariable('stat_data_prev_for', i);
                    }
                } catch { }
                let landed = 0;
                sets.forEach(l => { if (applySetLine(sd, l)) landed++; });
                bumpPendingDay(sd);
                reconcileRosterState(sd);
                await ctx.setVariable('stat_data', sd);   // 落账再返回——refresh 同步先跑时不能读旧值
                if (landed) { if (uiLedgerMiss) { uiLedgerMiss = false; saveUiPrefs(ctx); } }
                else { uiLedgerMiss = true; saveUiPrefs(ctx); console.log('[总簿] set 行写了但一条没落进——格式破得解析不了，当漏账催'); }
            } else if (uiLedgerMiss) { uiLedgerMiss = false; saveUiPrefs(ctx); }
            const kept = text.trim() ? text : '（……）';
            ledgerNote(i, raw, kept, sets);   // 剥皮前先留账底——分支滑回还要靠它重放
            if (text !== raw) {
                // 剥空的纯控制消息不能写 '' 进历史——上游按空 content 拒收就是 400，留个最小占位
                await ctx.editMessage?.(i, kept);
                stripMsgDom(i);   // 存储清了显示没清——气泡里的账皮顺手剥，判据与 splitSetLines 同一本
            }
        } catch (e) { console.warn('[总簿] set 行处理异常', e); }
    };

    /** 气泡剥壳：整段都是账/UV皮才摘，混文段保留——变体判据走 splitSetLines，不另起窄正则 */
    const stripMsgDom = (i) => {
        try {
            const doc = ctx.container?.ownerDocument;
            const box = doc?.querySelector?.(`.mes[mesid="${i}"] .mes_text`)
                ?? doc?.querySelectorAll?.('.mes_text')?.[doc.querySelectorAll('.mes_text').length - 1];
            if (!box) return;
            box.querySelectorAll('pre, code, p').forEach(el => {
                const t = el.textContent.trim();
                if (t && !splitSetLines(t).text.trim()) el.remove();
            });
            box.innerHTML = box.innerHTML.split(/<br\s*\/?>/i)
                .filter(seg => {
                    const t = seg.replace(/<[^>]+>/g, '').trim();
                    return !t || !!splitSetLines(t).text.trim();
                }).join('<br>');
        } catch { }
    };

    const et = ctx.lukerContext?.eventTypes || {};
    const EV = {
        genStart: et.GENERATION_STARTED ?? 'generation_started',
        wiFinal: et.GENERATION_WORLD_INFO_FINALIZED ?? 'generation_world_info_finalized',
        charMsg: et.CHARACTER_MESSAGE_RENDERED ?? 'character_message_rendered',
        userMsg: et.USER_MESSAGE_RENDERED ?? 'user_message_rendered',
        swiped: et.MESSAGE_SWIPED ?? 'message_swiped',
        deleted: et.MESSAGE_DELETED ?? 'message_deleted',
        chatChanged: et.CHAT_CHANGED ?? (ctx.parentDoc ? 'chat_id_changed' : 'chatChanged'),
    };

    // 上一条助手消息的账作废——换版/重生成/删消息时把 stat_data 退回快照；无快照（没写过账）则无事。
    // prev_for 名分校验：快照属于哪条记死了，回滚请求不是冲着它来的（比如删的是中间消息）就不许动
    const rollbackStat = async (forIdx) => {
        try {
            if (typeof ctx.getVariable !== 'function' || typeof ctx.setVariable !== 'function') return;
            const idx = forIdx ?? ((ctx.lukerContext?.chat?.length ?? 0) - 1);
            if (ctx.getVariable('stat_data_prev_for') !== idx) return;
            const prev = ctx.getVariable('stat_data_prev');
            await ctx.setVariable('stat_data_prev', null);
            await ctx.setVariable('stat_data_prev_for', null);
            if (prev && typeof prev === 'object') await ctx.setVariable('stat_data', prev);
            refresh();   // swiped 上同事件的 refresh 可能先按脏账渲了——滚完必须再渲一次收敛
        } catch { }
    };
    const clearPrev = async () => {
        try {
            await ctx.setVariable?.('stat_data_prev', null);
            await ctx.setVariable?.('stat_data_prev_for', null);
        } catch { }
    };
    // 每次生成前点名活跃弧（通道 C）；重生成/换版先回滚上一条的账，戏本和账都重来
    const arm = (type) => {
        if (/^(regenerate|swipe)$/i.test(String(type ?? ''))) rollbackStat();
        armForceActivate(ctx, model);
    };
    // 世界书 payload 拼装前，开场剧正文直推进去（模型漏不掉）
    const onWiFinal = payload => {
        try {
            // 开场戏第二条腿：点名通道是请求式的（emit 给引擎看脸色），payload 直推是自己往模型碗里放——
            // 引擎那端已在 payload 里（开场剧正文标记在）就跳过防双份；缺席则自己推，五幕必达
            if (num(model.day) <= 1) {
                const bag = payload?.worldInfoAfterEntries || payload?.worldInfoBeforeEntries;
                const op = _wiSorted?.find(e => /开场剧|落印五幕/.test(String(e.comment || e.name || '')));
                const content = op?.content || evtIdx['开场剧'];   // _wiSorted 未预热时走独立索引兜底
                if (bag && typeof bag.push === 'function' && content) {
                    const already = [...(payload.worldInfoAfterEntries || []), ...(payload.worldInfoBeforeEntries || [])]
                        .some(x => String(typeof x === 'string' ? x : (x?.content ?? '')).includes('落印后首轮'));
                    if (!already) { bag.push(content); console.log('[总簿] 开场剧经 payload 直推兜底'); }
                    else console.log('[总簿] 开场剧已在 payload（引擎点名生效），直推跳过');
                }
            }
        } catch { }
    };
    // 换版重放：stat_data_prev 语义 = 当前分支落账前的基线。切到别的分支=回基线+重放该分支的账，
    // 再按同一定位重立 prev（不能清——再滑一次还要滚回同一基线）。mesId 不指末位的不滚——prev 只描述末位账。
    const unpush = async (mesId) => {
        try {
            const chat = ctx.lukerContext?.chat;
            const last = (chat?.length ?? 0) - 1;
            if (mesId != null && Number.isFinite(Number(mesId)) && Number(mesId) !== last) return;   // mesId 非数字（JSR 传对象）就当没带，按末位处理
            const m = chat?.[last];
            // prev 只在它名下是末位时才滚——prev_for 指着别条说明末位没账，恢复它会误滚上一条
            const mine = ctx.getVariable?.('stat_data_prev_for') === last;
            const prev = mine ? ctx.getVariable?.('stat_data_prev') : null;
            await clearPrev();   // 先卸干净——下面按当前分支的账重立
            if (prev && typeof prev === 'object' && typeof ctx.setVariable === 'function')
                await ctx.setVariable('stat_data', prev);   // 回基线
            if (m && !m.is_user) {
                const raw = m.mes ?? m.message ?? '';
                const ent = ledgerEntry(last, raw);   // 先查账底——剥过皮的分支原文已净，只有底册里还有账
                const { text, sets } = ent ? { text: ent.kept, sets: ent.sets } : splitSetLines(raw);
                if (sets.length && typeof ctx.setVariable === 'function') {
                    const sd = ctx.getVariable?.('stat_data') || {};
                    try {
                        await ctx.setVariable('stat_data_prev', JSON.parse(JSON.stringify(sd)));
                        await ctx.setVariable('stat_data_prev_for', last);   // 各分支共享同一基线——照样记名下
                    } catch { }
                    sets.forEach(l => applySetLine(sd, l));
                    bumpPendingDay(sd);
                    reconcileRosterState(sd);
                    await ctx.setVariable('stat_data', sd);
                } else if (pendingAdvanceDay != null && typeof ctx.setVariable === 'function') {
                    const sd = ctx.getVariable?.('stat_data') || {};
                    const snap = JSON.parse(JSON.stringify(sd));
                    if (bumpPendingDay(sd)) {
                        try {
                            await ctx.setVariable('stat_data_prev', snap);
                            await ctx.setVariable('stat_data_prev_for', last);
                        } catch { }
                        await ctx.setVariable('stat_data', sd);
                    }
                }
                uiLedgerMiss = !sets.length; saveUiPrefs(ctx);
                const kept = String(text).trim() ? text : '（……）';
                if (!ent) ledgerNote(last, raw, kept, sets);   // 头一回见的分支——剥皮前先把账底记上
                if (text !== raw) {
                    await ctx.editMessage?.(last, kept);
                    stripMsgDom(last);
                }
            }
            refresh();
        } catch { }
    };
    // 删消息：只有删的是"最后一条助手消息"才滚账——prev 快照只描述它的增量；删中间消息滚了反而串账
    const onDeleted = () => {
        const chat = ctx.lukerContext?.chat;
        const last = chat?.[chat.length - 1];
        // 被删的那条下标=删后的 chat.length——prev 只滚它名下的账
        if (!chat?.length || last?.is_user) rollbackStat(chat?.length ?? 0);
    };
    if (ctx.eventSource?.on) {
        ctx.eventSource.on(EV.genStart, arm);
        ctx.eventSource.on(EV.wiFinal, onWiFinal);
        // 过日旗与弹窗草稿预缓存跨聊天必须清零，新局不串上局的账与未发草稿
        // 线宿主把每个楼层 diff 的兜底信号也发成 chat_changed（同局推送，参数仍是本局
        // chatFileName）——那不是换局，旗不能清；真换局才清（参数缺席时按旧语义保守清）
        const onChatChanged = (chatId) => {
            const cur = String(ctx.getChatId?.() ?? ctx.lukerContext?.chatId ?? '').replace(/\.jsonl$/i, '');
            const nxt = String(chatId ?? '').replace(/\.jsonl$/i, '');
            if (nxt && cur && nxt === cur) return;
            pendingAdvanceDay = null; pendingAdvanceOwnMsg = false;
            if (ctx.container) ctx.container.__intentDrafts = Object.create(null);
        };
        ctx.eventSource.on(EV.chatChanged, onChatChanged);
        ctx.eventSource.on(EV.swiped, unpush);
        ctx.eventSource.on(EV.deleted, onDeleted);
        // 两条宿主都严格串行「写完账 → 再渲染」：Luker 走 onCharMsgThenRefresh，JSR 走 ctx._afterCharMsg 回调
        const onCharMsgThenRefresh = async () => { await onCharMsg(); refresh(); };
        if (!ctx.parentDoc) ctx.eventSource.on(EV.charMsg, onCharMsgThenRefresh);
        else ctx._afterCharMsg = refresh;
        // 过日旗只在"下一条玩家消息落地"时收——若玩家「填进聊天框·度过今日」后又反悔删掉了度过今日，则立即撤销过日旗防误拨
        const onUserMsg = () => {
            if (pendingAdvanceOwnMsg) {
                pendingAdvanceOwnMsg = false;
                try {
                    const chat = ctx.lukerContext?.chat || [];
                    const lastUser = [...chat].reverse().find(m => m?.is_user);
                    const msgText = String(lastUser?.mes ?? lastUser?.message ?? '');
                    if (msgText && !/度过今日/.test(msgText)) pendingAdvanceDay = null;
                } catch { }
                refresh();   // 撤销过日旗后顺手重渲，托盘/门线与新状态对齐
                return;
            }
            pendingAdvanceDay = null;
            refresh();
        };
        ctx.eventSource.on(EV.userMsg, onUserMsg);
        // 注意：swiped/deleted/chatChanged 上面已各自注册过专属 handler，
        // 这里只补 userMsg 一路的 refresh——重复 on 同一事件会让旧 ctx 的
        // refresh 在换局后仍被触发（闭包捕获旧 model），且 _zbOff 清不干净。
        // charMsg 不在此列：两端均在落账完成后串行调用，避免并发读旧账。
        ctx._zbOff = () => {
            ctx.eventSource.removeListener(EV.charMsg, onCharMsgThenRefresh);
            ctx.eventSource.removeListener(EV.userMsg, onUserMsg);
            ctx.eventSource.removeListener(EV.swiped, unpush);
            ctx.eventSource.removeListener(EV.deleted, onDeleted);
            ctx.eventSource.removeListener(EV.chatChanged, onChatChanged);
        };
    }

    ctx.onDispose?.(() => {
        clearGateLine(ctx);
        _ovl.watchdog?.();
        if (ctx.eventSource?.removeListener) {
            ctx.eventSource.removeListener(EV.genStart, arm);
            ctx.eventSource.removeListener(EV.wiFinal, onWiFinal);
            ctx.eventSource.removeListener(EV.swiped, unpush);
            ctx.eventSource.removeListener(EV.deleted, onDeleted);
            ctx._zbOff?.();
            for (const ev of [EV.charMsg, EV.userMsg, EV.swiped, EV.deleted, EV.chatChanged]) {
                ctx.eventSource.removeListener(ev, refresh);
            }
        }
    });

    console.log(`[总簿] mounted · day=${model.day ?? '?'} · gate=${ctx.container.dataset.gate ?? '?'} · src=${model.fromText ? 'L2文本行' : model.empty ? 'empty' : 'stat_data'}`);
}
