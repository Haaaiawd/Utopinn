/**
 * 页四·背包：经营数据条 + 物品格。
 * 物化原则：钱/债/承诺/证据皆以物为单位——欠税单是债、借据是据、密信是信。
 * 点开看来历与状态，「处置」记拟办；了结的物由 runtime 移出，包里自然消失。
 * 牵扯账收进第二层：认得进物件的进物件条子（这笔账还牵着），谁也不认的
 * 并入格尾「他账凭据」。无「行囊」字段时，牵扯行仍降级成凭据卡，旧账一页不丢。
 */
function renderPack(ctx, model) {
    const pane = ctx.container.querySelector('[data-pane="3"]');
    const live = arr(model.items).filter(i => !isItemDone(i.status));
    const doneN = arr(model.items).length - live.length;
    const liveLedger = arr(model.ledger).filter(l => !l.done);
    const items = live.length ? live
        : liveLedger.map((l, i) => ({
            id: `lg${i}`, name: l.who, kind: LEDGER_KIND.find(([re]) => re.test(l.rel))?.[1] || '据',
            desc: l.what || l.rel, status: '持有', day: l.day, arc: '', use: '', rel: l.rel, led: i,
        }));

    // 账物相认（归一化包含匹配，两边任一沾上就算）：
    //   (对方+内容) 含有物名  或  (物名+物说) 含有对方——归一=去白去大小写，针至少两字
    const norm = s => String(s ?? '').toLowerCase().replace(/\s+/g, '');
    const itemLeds = items.map(() => []);   // 物件下标 → [liveLedger 下标]
    const housed = new Set();
    items.forEach((it, ii) => {
        if (it.led != null) housed.add(it.led);   // 凭据卡认领自家那本账，且不在条子里再列
        const name = norm(it.name), side = norm(`${it.name}${it.desc}`);
        liveLedger.forEach((l, li) => {
            if (li === it.led) return;
            const who = norm(l.who);
            if ((name.length >= 2 && norm(`${l.who}${l.what}`).includes(name))
                || (who.length >= 2 && side.includes(who))) {
                itemLeds[ii].push(li); housed.add(li);
            }
        });
    });
    const otherLeds = liveLedger.map((_, i) => i).filter(i => !housed.has(i));

    // 资源条不再摆第二遍——顶部状态条常驻四数，这里开门见格
    const debtN = items.filter(i => i.kind === '债').length;
    let html = `<div class="zb-secthead">行 囊 · ${items.length} 件${debtN ? ` <b class="zhu">（债 ${debtN}）</b>` : ''}</div>`;

    const cells = items.map((it, i) => {
        const k = itemKind(it.kind, it.name);
        const fresh = it.unread && !uiSeen.has(it.name);
        return `<button class="zb-item ${fresh ? 'unread' : ''}" data-item="${i}">
          <span class="zg ${k.cls}">${ico(k.icon)}</span>
          <span class="zn">${esc(it.name)}</span>
          ${fresh ? '<i class="znew">新</i>' : ''}
        </button>`;
    });
    // 没人认领的账归末格——虚框凭据卡，点开一页收
    if (otherLeds.length) cells.push(`<button class="zb-item zb-otherled" data-otherled>
          <span class="zg qing">${ico('据')}</span>
          <span class="zn">他账凭据</span>
          <span class="zsub">${otherLeds.length} 笔</span>
        </button>`);
    html += cells.length ? `<div class="zb-grid">${cells.join('')}</div>`
        : `<div class="zb-empty-mini">行囊空空——这倒也干净。</div>`;

    const doneLed = arr(model.ledger).filter(l => l.done);
    if (doneN || doneLed.length) html += `<div class="zb-done">已了结 ×${doneN}${doneLed.length ? `　<button type="button" class="zb-donled" data-donled>已了账 ×${doneLed.length}</button>` : ''}</div>`;
    html += `<div class="zb-card zb-icard"><div class="zb-empty-mini">点物件看底细，怎么处置记进拟办。</div></div>`;
    pane.innerHTML = html;

    // 账行 + 处置绑定：物件条子和「他账凭据」里同一笔法，别开两处
    const ledgerRow = (l, li) => `<div class="zb-lrow">
              <span class="lk">${esc(l.rel || '账')}</span><span class="lwho">${esc(l.who)}</span>
              <span class="lwhat">${esc(l.what)}</span>${l.day ? `<span class="lday">D${esc(l.day)}</span>` : ''}
              <button class="btn-seal sm" data-led="${li}">处置</button></div>`;
    const bindLed = scope => scope.querySelectorAll('[data-led]').forEach(b => b.addEventListener('click', () => {
        const l = liveLedger[Number(b.dataset.led)];
        if (l) openIntent(ctx, { title: `处理与${l.who}的账`, context: l.what || l.rel,
            question: '这笔账，你准备怎么处理？', placeholder: '例如：先核原据、商量延期、提出偿还办法，或写下你的方案。',
            format: text => `（就与${l.who}的这笔账，我准备：${text}）` });
    }));

    // 已了账档案：办结的牵扯不隐身，点开能查"我办过什么"
    pane.querySelector('[data-donled]')?.addEventListener('click', () => {
        openSheet(ctx, `已了账 · ${doneLed.length}笔`, doneLed.map(l => `<div class="zb-lrow done">
              <span class="lk">${esc(l.rel || '账')}</span><span class="lwho">${esc(l.who)}</span>
              <span class="lwhat">${esc(l.what)}</span>${l.day ? `<span class="lday">D${esc(l.day)}</span>` : ''}</div>`).join('') || '<div class="zb-none">暂无。</div>');
    });

    pane.querySelector('[data-otherled]')?.addEventListener('click', ev => {
        pane.querySelectorAll('[data-item],[data-otherled]').forEach(x => x.classList.remove('sel'));
        ev.currentTarget.classList.add('sel');
        openSheet(ctx, `没主的账 · ${otherLeds.length}笔`,
            otherLeds.map(li => ledgerRow(liveLedger[li], li)).join(''), bindLed);
    });

    // 物件明细走弹窗：格子只管"有几件、是什么"，来历状态翻条子看
    pane.querySelectorAll('[data-item]').forEach(b => b.addEventListener('click', () => {
        pane.querySelectorAll('[data-item],[data-otherled]').forEach(x => x.classList.remove('sel'));
        b.classList.add('sel');
        const ii = Number(b.dataset.item);
        const it = items[ii];
        if (it?.name && !uiSeen.has(it.name)) { uiSeen.add(it.name); saveUiPrefs(ctx); b.classList.remove('unread'); b.querySelector('.znew')?.remove(); }
        const k = itemKind(it.kind, it.name);
        const leds = itemLeds[ii] || [];
        openSheet(ctx, it.name, `
          <div class="sh-meta"><span class="stamp ${k.cls}">${esc(it.status)}</span>
            ${it.day ? `<span class="sh-mi">得于 第${esc(it.day)}天</span>` : ''}
            ${it.arc ? `<span class="sh-mi">涉 ${esc(it.arc)}</span>` : ''}</div>
          <div class="sh-desc">${esc(it.desc || '（没写来历）')}</div>
          ${leds.length ? `<div class="zb-itemled"><div class="sh-label">这笔账还牵着</div>${leds.map(li => ledgerRow(liveLedger[li], li)).join('')}</div>` : ''}
          ${it.use ? `<div class="sh-intent"><span class="sh-label">你记的用法</span>${esc(it.use)}</div>` : ''}
          <div class="zb-choices"><button class="btn-seal sm" data-use>${it.use ? '改改这个用法 →' : '写下这件东西怎么用 →'}</button></div>`, ov => {
            bindLed(ov);
            ov.querySelector('[data-use]').addEventListener('click', () => {
                openIntent(ctx, { title: `使用${it.name}`, context: it.desc || it.rel || '', question: '这件东西，你打算怎么用？',
                    initial: it.use || '', placeholder: '怎么用都行——抵押、换钱、喂炉、当幌子、搭配灵石/声望/士气整活，写明你的主意即可。', format: text => `（关于${it.name}，我准备：${text}）` });
            });
        });
    }));
}

