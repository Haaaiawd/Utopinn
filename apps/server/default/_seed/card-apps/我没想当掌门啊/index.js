    const isPour = () => curMode === 'pour';
    const old = ctx.container.querySelector('.zb-review');
    if (old) old.remove();
    const q = drafts(ctx);
    const st = readState(ctx);
    const due = arr(st.selfDuties).filter(d => (!d.day || d.day <= num(st.day)) && !uiSelfDone[d.thing]);
    const dutyLine = due.length ? `〔案头内参·勿引述〕案头日务「${due.map(d => d.thing).join('」「')}」今日到期——该了结的让它进戏，本条勿写入正文。` : '';
