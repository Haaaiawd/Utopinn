/** 名册指纹差分：新入门/有变动徽记；成长字段（境/资/注）同算，marks 进长命集看过才销 */
function rosterDiff(roster) {
    const now = {}, fresh = {};
    for (const d of roster) {
        const fp = `${d.post || ''}|${d.status || ''}|${d.trust ?? ''}|${d.realm || ''}|${d.apt || ''}|${d.note || ''}`;
        now[d.name] = fp;
        if (!(d.name in prevRoster)) fresh[d.name] = 'new';
        else if (prevRoster[d.name] !== fp) fresh[d.name] = 'chg';
    }
    const left = Object.keys(prevRoster).filter(n => !now[n]);
    prevRoster = now;
    for (const n of left) delete uiMarks[n];
    Object.assign(uiMarks, fresh);
    return { marks: uiMarks, left };
}

