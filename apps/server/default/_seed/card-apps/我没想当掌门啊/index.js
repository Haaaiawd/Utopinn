/** 通用弹窗：复用揭页浮层样式，点遮罩/「先放着」关 */
function openSheet(ctx, title, bodyHtml, onBind) {
    ctx.container.querySelector('.zb-sheet')?.remove();
    const ov = document.createElement('div');
    ov.className = 'zb-review zb-sheet';
    ov.style.top = ctx.container.ownerDocument.defaultView.getComputedStyle(ctx.container).paddingTop;
    ov.innerHTML = `<div class="rv-paper" role="dialog" aria-modal="true" aria-label="${esc(title)}" tabindex="-1"><div class="rv-hd">${esc(title)}</div><div class="sh-content">${bodyHtml}</div><div class="sh-footer"><button class="rv-back">先放着</button></div></div>`;
    ctx.container.appendChild(ov);
    const previous = ov.ownerDocument.activeElement;
    const close = () => { ov.remove(); if (previous?.isConnected) previous.focus?.(); };
    ov.querySelector('.rv-back').onclick = close;
    ov.addEventListener('click', e => { if (e.target === ov) close(); });
    ov.addEventListener('keydown', e => {
        if (e.key === 'Escape') { e.preventDefault(); e.stopPropagation(); close(); }
        if (e.key !== 'Tab') return;
        const focusable = [...ov.querySelectorAll('button:not(:disabled), input, textarea, [tabindex="0"]')].filter(el => el.getClientRects().length);
        const first = focusable[0], last = focusable[focusable.length - 1];
        if (e.shiftKey && (ov.ownerDocument.activeElement === first || ov.ownerDocument.activeElement === ov.firstElementChild)) { e.preventDefault(); last?.focus(); }
        else if (!e.shiftKey && ov.ownerDocument.activeElement === last) { e.preventDefault(); first?.focus(); }
    });
    onBind?.(ov);
    ov.firstElementChild.focus();
    return ov;
}

