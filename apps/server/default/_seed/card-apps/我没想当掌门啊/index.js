/** 建筑解锁/升级差分：废/修→开 记 'unlock'；级/升次/词条增加 记 'up'，点开该建筑才销标 */
function facilityDiff(facilities) {
    const list = arr(facilities);
    if (!list.length) return uiFacMarks;
    const hasBase = !!prevFacSt.__init;
    const next = { __init: 1 };
    for (const f of list) {
        const fp = `${f.st}|${f.lv}|${f.upgrades}|${arr(f.traits).join(',')}`;
        next[f.place] = fp;
        if (!hasBase) continue;
        const old = prevFacSt[f.place];
        if (!old || old === fp) continue;
        const [ost, olv, oup, otr] = old.split('|');
        const oldTraits = otr ? otr.split(',').filter(Boolean).length : 0;
        if ((ost === '废' || ost === '修') && f.st === '开') uiFacMarks[f.place] = 'unlock';
        else if (f.st === '开' && (ost === '升' || f.lv > num(olv) || f.upgrades > num(oup) || arr(f.traits).length > oldTraits)) uiFacMarks[f.place] = 'up';
    }
    prevFacSt = next;
    return uiFacMarks;
}

