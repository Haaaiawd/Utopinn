/** 把模糊/带后缀的肖像键归一到真实文件名（去 .webp、模糊匹配脸池） */
function resolveFaceKey(rawLike, name) {
    const nm = String(name || '').trim();
    if (NAMED_FACES.has(nm)) return nm;
    const raw = String(rawLike || '').trim().replace(/\.webp$/i, '').replace(/^.*\//, '');
    if (!raw) return '';
    if (ALL_KNOWN_FACES.has(raw)) return raw;
    const compact = raw.replace(/[_＿\s-]+/g, '');
    if (NAMED_FACES.has(compact)) return compact;
    const hit = ALL_POOL_FACES.find(k => k.replace(/_/g, '') === compact || k.includes(raw) || (compact.length >= 2 && k.replace(/_/g, '').includes(compact)));
    return hit || '';
}

/** 根据弟子岗位/备注从未用脸池优先挑最贴脸的立绘，彻底避免空白头像与撞脸 */
function pickUnusedFace(d, used, poolD, poolC) {
    const avail = [...(poolD || []), ...(poolC || [])].filter(k => ALL_KNOWN_FACES.has(k) && !used.has(k));
    const fallback = ALL_POOL_FACES.filter(k => !used.has(k));
    const cands = avail.length ? avail : fallback;
    if (!cands.length) return '';
    const hint = `${d['差事'] || d.post || ''}${d['状态'] || d.status || ''}${d['注'] || d.note || ''}${d['名'] || d.name || ''}`;
    const rules = [
        [/炉|丹|药|火|匠|工坊/, /药修|工坊师傅/],
        [/账|算|钱|财|商/, /账修|算子|老吏账房|精明商妇/],
        [/田|农|草|植|菜/, /田修/],
        [/剑|刀|演武|护院|武|战/, /剑修|刀修/],
        [/符|阵|书|文|库|抄/, /符修|怀才书生|师姐/],
        [/夜|暗|探|侦|哨|后山/, /夜行/],
        [/女|妹|姐|娘|姑/, /女|少女|商妇/],
        [/男|哥|兄|汉|老/, /男|少年|汉子|老吏|老仆|书生/],
    ];
    for (const [hRe, fRe] of rules) {
        if (hRe.test(hint)) {
            const matched = cands.find(k => fRe.test(k));
            if (matched) return matched;
        }
    }
    let h = 0;
    const seed = String(d['名'] || d.name || 'x');
    for (let i = 0; i < seed.length; i++) h = (h * 31 + seed.charCodeAt(i)) >>> 0;
    return cands[h % cands.length];
}

/** 落账后自动校准名册：补齐入门日、统一肖像键并从脸池扣减防撞脸（原地修改 sd，返回是否有改动） */
function reconcileRosterState(sd) {
    if (!sd || typeof sd !== 'object') return false;
    const roster = objArr(sd['名册']);
    if (!roster.length) return false;
    let changed = false;
    const dayN = num(sd.day ?? sd['天数']) || 1;
    if (!sd['脸池'] || typeof sd['脸池'] !== 'object') sd['脸池'] = { '弟子': [...INIT_FACE_POOL['弟子']], '众生': [...INIT_FACE_POOL['众生']] };
    const poolD = arr(sd['脸池']['弟子']).filter(x => typeof x === 'string');
    const poolC = arr(sd['脸池']['众生']).filter(x => typeof x === 'string');
    const used = new Set();
    // 第一遍：先登记命名角色和合法已领脸，防止重复领同一张
    for (const d of roster) {
        if ((d['入'] == null || d['入'] === '') && dayN > 0) { d['入'] = dayN; changed = true; }
        const resolved = resolveFaceKey(d['像'], d['名'] ?? d.name);
        if (resolved && (!used.has(resolved) || NAMED_FACES.has(resolved))) {
            if (d['像'] !== resolved) { d['像'] = resolved; changed = true; }
            used.add(resolved);
        } else if (d['像']) {
            d['像'] = ''; changed = true;   // 无效或撞脸键清空，交由第二遍重配
        }
    }
    // 第二遍：给无像弟子自动从未用脸池分配
    for (const d of roster) {
        if (!d['像']) {
            const picked = pickUnusedFace(d, used, poolD, poolC);
            if (picked) { d['像'] = picked; used.add(picked); changed = true; }
        }
    }
    // 从脸池划去所有已占用的脸，彻底防撞脸
    const nextD = poolD.filter(k => !used.has(k));
    const nextC = poolC.filter(k => !used.has(k));
    if (nextD.length !== poolD.length) { sd['脸池']['弟子'] = nextD; changed = true; }
    if (nextC.length !== poolC.length) { sd['脸池']['众生'] = nextC; changed = true; }
    return changed;
}

/** 统一格式化弟子信任度（数字+档位词）与月例 */
const TRUST_WORD_MAP = [
    [/死忠|生死|铁杆|肝胆/, 90],
    [/信赖|信任|亲近|熟稔|贴心/, 75],
    [/认可|顺心|卖力|踏实|安心/, 60],
    [/初识|刚来|新入|一般|尚可|观望/, 40],
    [/戒备|警惕|动摇|不满|疏远|怀疑/, 20],
];
function formatTrust(raw) {
    if (raw == null || raw === '') return '40 · 初识';
    const s = String(raw).trim();
    const m = s.match(/-?\d+/);
    let score = m ? Number(m[0]) : null;
    if (score == null) {
        const hit = TRUST_WORD_MAP.find(([re]) => re.test(s));
        score = hit ? hit[1] : 40;
    }
    score = Math.max(0, Math.min(100, Math.round(score)));
    const tier = score >= 85 ? '死忠' : score >= 70 ? '信赖' : score >= 50 ? '认可' : score >= 30 ? '初识' : '戒备';
    return `${score} · ${tier}`;
}
function formatSalary(raw) {
    if (raw == null || raw === '') return '0 灵石/月（管吃住）';
    const s = String(raw).trim();
    if (/^\d+(?:\.\d+)?$/.test(s)) {
        const n = Number(s);
        return n === 0 ? '0 灵石/月（管吃住）' : `${n} 灵石/月`;
    }
    if (/^(0|无|免|包吃|管吃|管饭|管.*饭|管.*顿)/.test(s)) return `0 灵石/月（${s}）`;
    return s;
}

