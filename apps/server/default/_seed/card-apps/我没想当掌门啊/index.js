function readState(ctx) {
    const sd = safeGet(() => ctx.getVariable?.('stat_data'));
    if (sd && typeof sd === 'object' && Object.keys(sd).length) {
        const m = normalizeStatData(sd);
        // L2 文本行只在 L1 没立起来时才去翻——有 day+宗名说明模型在维护 stat_data，
        // 此时 due/today/ledger 空就是"真没有"而非"没写到"，全量扫聊天纯属白跑
        const needRows = !m.day || !m.sect;
        const rows = needRows ? parseTextRows(ctx) : null;
        if (rows) {
            m.day = m.day || rows.day;
            if (!m.res || !Object.keys(m.res).length) m.res = rows.res;
            if (!m.roster.length && rows.roster) m.roster = rows.roster;
            if (!Object.keys(m.arcs || {}).length && rows.arcs) m.arcs = rows.arcs;
            if (!m.due.length && rows.due) m.due = rows.due;
            if (!m.today && rows.today) m.today = rows.today;
            if (!m.ledger.length && rows.ledger) m.ledger = rows.ledger;
        }
        return m;
    }
    const rows = parseTextRows(ctx);
    if (rows) return rows;
    return { empty: true };
}

