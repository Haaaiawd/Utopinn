function deadlineInfo(value, day) {
    const raw = String(value ?? '').trim();
    const match = raw.match(/^(?:D\s*(\d+)|第?\s*(\d+)\s*天?|(\d+))\s*(?:截(?:止)?)?$/i);
    const due = match ? Number(match[1] ?? match[2] ?? match[3]) : null;
    if (due == null) return { label: raw || '没说期限', urgent: false, due: Infinity };
    const left = due - num(day);
    return { label: left < 0 ? `已过期 ${-left} 天` : left === 0 ? '今日截止' : `余 ${left} 天`, urgent: left <= 0, due };
}

function pendingByDeadline(model) {
    return [...arr(model.due)].sort((a, b) => deadlineInfo(a.ddl, model.day).due - deadlineInfo(b.ddl, model.day).due);
}

